Deno.serve(async (req) => {
  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();

    if (!user || (user.role !== 'admin' && user.access_level !== 'admin' && user.access_level !== 'super_admin')) {
      return Response.json({ error: 'Unauthorized - Admin only' }, { status: 403 });
    }

    const { force = false } = await req.json().catch(() => ({}));

    const templates = await base44.asServiceRole.entities.TemplateLibrary.list();
    
    let updated = 0;
    let skipped = 0;
    const updatedList = [];
    const errors = [];

    for (const template of templates) {
      try {
        const seed = THAI_TEMPLATE_SEEDS[template.template_key];
        
        if (!seed) {
          continue;
        }

        const hasExistingThai = template.document_content_th && 
                                template.document_content_th.trim().length >= 300;

        if (hasExistingThai && !force) {
          skipped++;
          continue;
        }

        await base44.asServiceRole.entities.TemplateLibrary.update(template.id, {
          preview_content_th: seed.preview_content_th,
          document_content_th: seed.document_content_th
        });

        updated++;
        updatedList.push(template.template_key);
      } catch (error) {
        errors.push({
          template_key: template.template_key,
          error: error.message
        });
      }
    }

    return Response.json({
      success: true,
      summary: {
        total_templates: templates.length,
        updated_count: updated,
        skipped_count: skipped,
        errors_count: errors.length
      },
      updated_templates: updatedList,
      errors: errors,
      message: `Successfully seeded ${updated} Thai templates. ${skipped} skipped (already had Thai content). ${errors.length} errors.`
    });

  } catch (error) {
    console.error('Thai seed error:', error);
    return Response.json({
      error: error.message,
      stack: error.stack
    }, { status: 500 });
  }
});